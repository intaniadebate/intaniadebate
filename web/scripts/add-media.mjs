import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import sharp from 'sharp';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { values } = parseArgs({ options: { id: { type: 'string' }, file: { type: 'string' }, alt: { type: 'string' }, caption: { type: 'string', default: '' }, credit: { type: 'string', default: '' }, approved: { type: 'boolean', default: false } } });
if (!values.id || !/^[a-zA-Z0-9_-]+$/.test(values.id) || !values.file || !values.alt?.trim()) throw new Error('Use --id=safe-id --file="absolute image path" --alt="description" [--approved]');
const file = await fs.realpath(path.resolve(values.file));
const catalogPath = path.join(root, 'src', 'data', 'media.json');
const catalog = JSON.parse(await fs.readFile(catalogPath, 'utf8'));
if (catalog[values.id]) throw new Error('ID already exists. Choose a new ID to preserve existing references.');
const meta = await sharp(file).metadata();
const rotated = meta.orientation >= 5 && meta.orientation <= 8;
const width = rotated ? meta.height : meta.width;
const height = rotated ? meta.width : meta.height;
if (!width || !height) throw new Error('Image dimensions unavailable');
const sourcePath = path.join(root, '.local', 'media-sources.json');
const sources = JSON.parse(await fs.readFile(sourcePath, 'utf8').catch(() => '{}'));
catalog[values.id] = { width, height, alt: values.alt.trim(), caption: values.caption, credit: values.credit, kind: 'photo', publishable: values.approved, local: null, variants: [] };
sources[values.id] = file;
await fs.mkdir(path.dirname(sourcePath), { recursive: true });
await fs.writeFile(sourcePath, JSON.stringify(sources, null, 2) + '\n');
await fs.writeFile(catalogPath, JSON.stringify(catalog, null, 2) + '\n');
console.log(`Registered ${values.id} (${width} × ${height}); ${values.approved ? 'approved for publishing' : 'local preview only'}. Restart npm run dev to prepare derivatives.`);
