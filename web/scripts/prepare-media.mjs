import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export async function prepareMedia(preview = false) {
  const target = path.resolve(root, preview ? '.local-public' : 'public');
  if (path.dirname(target) !== root || !['public', '.local-public'].includes(path.basename(target))) throw new Error('Unexpected generated-media directory');
  await fs.mkdir(path.join(target, 'media'), { recursive: true });
  for (const name of ['preferences.js', '_headers', 'favicon.png']) await fs.copyFile(path.join(root, 'static', name), path.join(target, name));
  await fs.mkdir(path.join(target, 'licenses'), { recursive: true });
  for (const name of ['Noto-Sans-Thai-OFL.txt', 'Cormorant-Garamond-OFL.txt']) await fs.copyFile(path.join(root, 'static', 'licenses', name), path.join(target, 'licenses', name));
  const manifestPath = path.join(root, 'src', 'data', 'media.json');
  const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'));
  const sources = JSON.parse(await fs.readFile(path.join(root, '.local', 'media-sources.json'), 'utf8').catch(() => '{}'));
  const portableMedia = path.join(root, 'static', 'media');
  await fs.mkdir(portableMedia, { recursive: true });
  for (const filename of await fs.readdir(portableMedia)) {
    const match = filename.match(/^([a-zA-Z0-9_-]+)-(\d+)\.webp$/);
    if (match && manifest[match[1]]?.publishable) await fs.copyFile(path.join(portableMedia, filename), path.join(target, 'media', filename));
  }
  // Remove stale generated derivatives when permission is revoked or an asset is removed.
  // Only exact files generated by this script inside the checked media directory qualify.
  for (const filename of await fs.readdir(path.join(target, 'media'))) {
    const match = filename.match(/^([a-zA-Z0-9_-]+)-(\d+)\.webp$/);
    if (!match) continue;
    const asset = manifest[match[1]];
    if (!asset || (!preview && !asset.publishable)) await fs.unlink(path.join(target, 'media', filename));
  }
  let count = 0;
  for (const [id, asset] of Object.entries(manifest)) {
    if (!preview && !asset.publishable) continue;
    if (!sources[id]) continue;
    if (!/^[a-zA-Z0-9_-]+$/.test(id)) throw new Error('Unsafe media ID');
    const metadata = await sharp(sources[id]).metadata();
    const widths = [...new Set([Math.min(640, metadata.width), Math.min(1440, metadata.width)])].sort((a, b) => a - b);
    asset.variants = [];
    for (const width of widths) {
      const filename = `${id}-${width}.webp`;
      const output = path.join(target, 'media', filename);
      const inputStat = await fs.stat(sources[id]);
      const outputStat = await fs.stat(output).catch(() => null);
      if (!outputStat || outputStat.mtimeMs < inputStat.mtimeMs) await sharp(sources[id]).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 84 }).toFile(output);
      if (asset.publishable) await fs.copyFile(output, path.join(portableMedia, filename));
      asset.variants.push({ src: `/media/${filename}`, width });
    }
    asset.local = asset.variants.at(-1).src;
    count++;
  }
  await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  console.log(`Media: ${count} assets prepared for ${preview ? 'local preview' : 'production'} (unapproved assets excluded from production)`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await prepareMedia(process.argv.includes('--preview'));
